package ai

import (
	"context"
	"time"

	"cloudprep-backend/internal/models"
)

// GenerationRequest contains parameters for generating curriculum-grounded questions.
type GenerationRequest struct {
	TopicID       string   `json:"topicId"`
	ObjectiveID   string   `json:"objectiveId,omitempty"`
	QuestionStyle string   `json:"questionStyle"` // DEFINITION, COMMAND_SYNTAX, COMPARISON, SCENARIO
	Difficulty    string   `json:"difficulty"`    // EASY, MEDIUM, HARD
	Count         int      `json:"count"`
	AvoidStems    []string `json:"avoidStems,omitempty"`
}

// GeneratedOption represents one of the 4 options in an AI-generated question.
type GeneratedOption struct {
	Key                 string `json:"key"` // A, B, C, D
	Text                string `json:"text"`
	DistractorRationale string `json:"distractorRationale"`
}

// GeneratedQuestion represents a single question generated by an AI model.
type GeneratedQuestion struct {
	Stem             string            `json:"stem"`
	QuestionStyle    string            `json:"questionStyle"`
	Difficulty       string            `json:"difficulty"`
	CognitiveSkill   string            `json:"cognitiveSkill"`
	ScenarioType     string            `json:"scenarioType,omitempty"`
	CorrectOptionKey string            `json:"correctOptionKey"`
	Explanation      string            `json:"explanation"`
	SourceReference  string            `json:"sourceReference"`
	Options          []GeneratedOption `json:"options"`
}

// GenerationResult represents the raw and parsed outcome of an AI generation call.
type GenerationResult struct {
	Provider     string              `json:"provider"` // gemini or groq
	ModelID      string              `json:"modelId"`
	FailoverUsed bool                `json:"failoverUsed"`
	Questions    []GeneratedQuestion `json:"questions"`
	DurationMs   int64               `json:"durationMs"`
	RawResponse  string              `json:"rawResponse,omitempty"`
}

// QuestionGenerationProvider is the common interface implemented by Gemini and Groq adapters.
type QuestionGenerationProvider interface {
	ProviderName() string
	ModelID() string
	IsConfigured() bool
	GenerateQuestions(ctx context.Context, req GenerationRequest, topic models.CurriculumTopic, excerpts []string) (*GenerationResult, error)
}

// ValidationResult captures the outcome of verifying an AI-generated question.
type ValidationResult struct {
	IsValid            bool
	NormalizedStem     string
	ContentFingerprint string
	RejectionReason    string
}

// ReplenishmentJob represents a request to replenish a topic's question pool.
type ReplenishmentJob struct {
	TopicID       string
	QuestionStyle string
	Difficulty    string
	TriggeredAt   time.Time
}

